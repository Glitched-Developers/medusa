/// Приводит текст с сайта к аккуратному виду: убирает неразрывные пробелы,
/// схлопывает повторы пробелов и обрезает края.
///
/// Сайт БелГУ щедро расставляет `&nbsp;` и переводы строк внутри ячеек,
/// поэтому одну и ту же чистку используют парсер расписания, поиск
/// преподавателей и новости.
String normalizeSpaces(String value) =>
    value.replaceAll('\u00a0', ' ').replaceAll(RegExp(r'\s+'), ' ').trim();
